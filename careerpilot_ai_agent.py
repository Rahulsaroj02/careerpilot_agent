"""#Project Recommendation Node"""

def project_recommendation_node(state: CareerState) -> CareerState:

    role = state["target_role"].lower()

    filtered_projects = projects_df[
        projects_df["target_roles"].str.lower().str.contains(role, na=False)
    ]

    recommended_projects = filtered_projects["project_name"].tolist()

    return {
        **state,
        "recommended_projects": recommended_projects
    }

"""#Final Report Node"""

def final_report_node(state: CareerState) -> CareerState:

    report = FINAL_REPORT_TEMPLATE.format(
        name=state["name"],
        education=state["education"],
        target_role=state["target_role"],
        current_skills=", ".join(state["current_skills"]),
        required_skills=", ".join(state["required_skills"]),
        missing_skills=", ".join(state["missing_skills"]),
        reasoning=state["reasoning"],
        roadmap=state["roadmap"],
    )

    for project in state["recommended_projects"]:
        report += FINAL_REPORT_PROJECT_LINE.format(project=project)

    report += FINAL_REPORT_FOOTER

    print(report)

    return {
        **state,
        "final_report": report
    }

"""#Build the Graph"""

from langgraph.graph import StateGraph, END

builder = StateGraph(CareerState)

# Nodes
