builder.add_node("role_match", role_matching_node)      # NEW
builder.add_node("skill_analysis", skill_analysis_node)
builder.add_node("roadmap", roadmap_node)
builder.add_node("projects", project_recommendation_node)
builder.add_node("report", final_report_node)

# Entry Point
builder.set_entry_point("intake")

# Flow
builder.add_edge("intake", "role_match")
builder.add_edge("role_match", "skill_analysis")
builder.add_edge("skill_analysis", "roadmap")
builder.add_edge("roadmap", "projects")
builder.add_edge("projects", "report")
builder.add_edge("report", END)

graph = builder.compile()

